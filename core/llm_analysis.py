import re
import requests

OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL = "llama3"


def ask_llm(prompt: str) -> str:
    response = requests.post(
        OLLAMA_URL,
        json={"model": MODEL, "prompt": prompt, "stream": False},
    )

    data = response.json()
    return data.get("response", "").strip()


def clean_transcript_for_llm(text: str) -> str:
    """
    Чистим мусор распознавания перед LLM:
    - убираем таймкоды
    - убираем длинные повторы типа "да, да, да"
    - убираем длинные повторы фраз типа "будет лучше"
    - слегка нормализуем пробелы
    """

    if not text:
        return ""

    cleaned = text

    # Убираем таймкоды вида [292.6s]
    cleaned = re.sub(r"\[\d+(?:\.\d+)?s\]\s*", "", cleaned)

    # Убираем длинные серии "да, да, да..."
    cleaned = re.sub(
        r"\b(да|нет|ага|угу|ну)\b(?:[\s,\.]+(?:да|нет|ага|угу|ну)\b){3,}",
        r"\1",
        cleaned,
        flags=re.IGNORECASE,
    )

    # Убираем длинные повторы коротких фраз: "будет лучше. будет лучше..."
    cleaned = re.sub(
        r"\b(.{3,40}?)\b(?:[\s,\.]+?\1\b){3,}",
        r"\1",
        cleaned,
        flags=re.IGNORECASE,
    )

    # Убираем слишком длинные цепочки одинаковых слов
    cleaned = re.sub(
        r"\b(\w+)\b(?:[\s,\.]+?\1\b){3,}",
        r"\1",
        cleaned,
        flags=re.IGNORECASE,
    )

    # Нормализация пробелов
    cleaned = re.sub(r"[ \t]+", " ", cleaned)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)

    return cleaned.strip()


