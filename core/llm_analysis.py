# ================= TASKS =================
def extract_tasks(text: str):
    cleaned_text = clean_transcript_for_llm(text)

    prompt = f"""
Ты — бизнес-аналитик совещаний.

Отвечай строго на русском языке.
Используй русский язык для формулировок.

Определи, является ли текст деловой встречей, рабочим обсуждением или разговором по делу.

Если это песня, шум, случайная речь или текст без делового смысла:
напиши ровно:
NO_TASKS

Если это деловая встреча или рабочий разговор:
выдели практические задачи и следующие действия.

ВАЖНО:
Задача может быть выражена не прямой командой, а как договорённость, намерение или следующий шаг.

Примеры задач:
- Связаться с адвокатом
- Направить условия по почте
- Озвучить позицию в суде
- Уточнить сумму прямых затрат
- Подготовить условия возможного соглашения
- Проверить вариант обеспечения обязательств

ПРАВИЛА:
- Каждая строка = одна задача.
- Начинай с глагола в неопределённой форме.
- Формулируй как конкретное действие.
- Не добавляй исполнителя, если он явно не указан.
- Не добавляй сроки, если они явно не указаны.
- Не выдумывай факты.
- Убирай повторы.
- Не пиши пояснений.
- Не пиши заголовки.

Если встреча деловая, но задачи выражены косвенно — выдели 1–5 вероятных следующих действий.
NO_TASKS пиши только если это точно не деловая встреча.
Для деловой встречи обязательно верни хотя бы 1 задачу.
Даже если задачи выражены неявно, сформулируй следующий логичный шаг.

Текст:
{cleaned_text}
"""

    raw = ask_llm(prompt)

    if "NO_TASKS" in raw:
        raw = ""

    lines = raw.split("\n")

    tasks = []

    for line in lines:
        cleaned = line.strip().strip("-•* ").strip()
        cleaned = re.sub(r"^\d+\.\s*", "", cleaned)

        if not cleaned:
            continue

        if len(cleaned.split()) < 2:
            continue

        forbidden_starts = [
            "присутствовать",
            "выступить",
            "выступал",
            "доклад",
        ]

        cleaned_lower = cleaned.lower()

        if any(cleaned_lower.startswith(word) for word in forbidden_starts):
            continue

        if any(word in cleaned_lower for word in ["доклад", "присутствовать"]):
            continue

        tasks.append(cleaned)

    return tasks
